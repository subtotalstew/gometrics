// Command reset генерирует методы Reset() для структур, помеченных
// комментарием // generate:reset.
//
// # Запуск
//
//	go run ./cmd/reset
//
// Утилита рекурсивно обходит все пакеты начиная с корневой директории
// проекта, находит структуры с директивой // generate:reset и генерирует
// для каждой метод Reset(), записывая результаты в reset.gen.go внутри
// соответствующего пакета.
//
// # Правила сброса
//
//   - примитивы (int, string, bool, ...) — к нулевому значению;
//   - слайсы — обрезаются по длине: s = s[:0];
//   - мапы — очищаются через clear(m);
//   - указатели — если не nil, то *ptr сбрасывается по тем же правилам;
//   - вложенные структуры — вызывают Reset(), если он у них есть;
//   - sync-типы (sync.Mutex, sync.RWMutex, sync.Once, sync.WaitGroup,
//     sync.Pool, sync.Cond) — пропускаются как не имеющие состояния;
//   - поля без имени (embed) — пропускаются.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"
)

const directive = "generate:reset"
const generatedFileName = "reset.gen.go"

// skipTypes — типы из пакета sync, которые не нужно сбрасывать.
// Присваивание zero value мьютексу или once может сломать синхронизацию.
var skipTypes = map[string]bool{
	"sync.Mutex":     true,
	"sync.RWMutex":   true,
	"sync.Once":      true,
	"sync.WaitGroup": true,
	"sync.Pool":      true,
	"sync.Cond":      true,
	"sync.Map":       true,
}

// resetTemplate — шаблон генерируемого файла.
//
// В одном месте видно:
//   - заголовок «Code generated ...; DO NOT EDIT.»;
//   - блок import (только если он нужен);
//   - методы Reset() для каждой структуры пакета.
//
// Структура {{.Package}} — имя пакета. {{range .Structs}} обходит
// структуры, у каждой есть поля Name (имя типа) и Fields — список
// полей с готовым выражением сброса (Expr) и комментарием (Comment).
const resetTemplate = `// Code generated by cmd/reset; DO NOT EDIT.

package {{.Package}}
{{if .Imports}}
import (
{{- range .Imports}}
	{{printf "%q" .Path}}
{{- end}}
)
{{end}}
{{range .Structs}}
// Reset сбрасывает {{.Name}} к начальному состоянию.
func (x *{{.Name}}) Reset() {
	if x == nil {
		return
	}
{{range .Fields}}
	// {{.Name}}
	{{.Expr}}
{{end -}}
}
{{end}}
`

// pkgInfo — собранная информация о пакете: путь, имя, найденные структуры.
type pkgInfo struct {
	dir     string
	name    string
	structs []*structInfo
}

// structInfo — структура, для которой нужно сгенерировать Reset().
type structInfo struct {
	name   string
	fields []*ast.Field
}

// templateData — данные для text/template. Всё, что нужно шаблону,
// уже «плоское»: строки, срезы строк, готовые выражения.
type templateData struct {
	Package string
	Imports []importInfo
	Structs []structTemplateData
}

type structTemplateData struct {
	Name   string
	Fields []fieldTemplateData
}

type fieldTemplateData struct {
	Name string // имя поля (для комментария)
	Expr string // готовое выражение сброса, например: `x.gauge = 0`
}

type importInfo struct {
	Path string
	Name string
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "reset:", err)
		os.Exit(1)
	}
}

func run() error {
	root, err := os.Getwd()
	if err != nil {
		return fmt.Errorf("getwd: %w", err)
	}

	pkgs, err := scanPackages(root)
	if err != nil {
		return err
	}

	for _, pkg := range pkgs {
		if len(pkg.structs) == 0 {
			continue
		}
		if err := renderPackage(pkg); err != nil {
			return fmt.Errorf("package %s: %w", pkg.name, err)
		}
	}
	return nil
}

// scanPackages рекурсивно обходит root и собирает пакеты с директивами.
func scanPackages(root string) ([]*pkgInfo, error) {
	var pkgs []*pkgInfo

	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		base := filepath.Base(path)
		if base == "vendor" || base == ".git" || base == "testdata" || strings.HasPrefix(base, ".") {
			return filepath.SkipDir
		}

		pkg, err := parseDir(path)
		if err != nil {
			return err
		}
		if pkg != nil && len(pkg.structs) > 0 {
			pkgs = append(pkgs, pkg)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	return pkgs, nil
}

// parseDir разбирает все .go-файлы директории (кроме *_test.go и
// сгенерированных reset.gen.go) и возвращает pkgInfo, если найдены
// структуры с директивой.
func parseDir(dir string) (*pkgInfo, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}

	fset := token.NewFileSet()
	var (
		pkgName string
		structs []*structInfo
	)

	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		name := e.Name()
		if !strings.HasSuffix(name, ".go") {
			continue
		}
		if strings.HasSuffix(name, "_test.go") || name == generatedFileName {
			continue
		}

		full := filepath.Join(dir, name)
		file, err := parser.ParseFile(fset, full, nil, parser.ParseComments)
		if err != nil {
			return nil, fmt.Errorf("parse %s: %w", full, err)
		}

		if pkgName == "" {
			pkgName = file.Name.Name
		}

		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			if !hasDirective(gd.Doc) {
				continue
			}
			for _, spec := range gd.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				st, ok := ts.Type.(*ast.StructType)
				if !ok {
					continue
				}
				structs = append(structs, &structInfo{
					name:   ts.Name.Name,
					fields: st.Fields.List,
				})
			}
		}
	}

	if pkgName == "" || len(structs) == 0 {
		return nil, nil
	}
	return &pkgInfo{dir: dir, name: pkgName, structs: structs}, nil
}

func hasDirective(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}
	for _, c := range doc.List {
		text := strings.TrimSpace(strings.TrimPrefix(c.Text, "//"))
		if strings.HasPrefix(text, directive) {
			return true
		}
	}
	return false
}

// renderPackage готовит данные и рендерит reset.gen.go для пакета.
func renderPackage(pkg *pkgInfo) error {
	data := buildTemplateData(pkg)

	tmpl, err := template.New("reset").Parse(resetTemplate)
	if err != nil {
		return fmt.Errorf("parse template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return fmt.Errorf("execute template: %w", err)
	}

	// gofmt: text/template не гарантирует идеальные отступы,
	// особенно в ветках if/range. format.Source выравнивает.
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format: %w\nraw:\n%s", err, buf.String())
	}

	out := filepath.Join(pkg.dir, generatedFileName)
	return os.WriteFile(out, formatted, 0o644)
}

// buildTemplateData собирает «плоские» данные для шаблона.
func buildTemplateData(pkg *pkgInfo) templateData {
	data := templateData{
		Package: pkg.name,
		Imports: collectImports(pkg),
	}

	for _, s := range pkg.structs {
		sd := structTemplateData{Name: s.name}
		for _, f := range s.fields {
			if len(f.Names) == 0 || isSyncType(f.Type) {
				continue
			}
			for _, name := range f.Names {
				sd.Fields = append(sd.Fields, fieldTemplateData{
					Name: name.Name,
					Expr: resetExpr("x."+name.Name, f.Type),
				})
			}
		}
		data.Structs = append(data.Structs, sd)
	}

	// Сортируем структуры и импорты для детерминированного вывода.
	sort.Slice(data.Structs, func(i, j int) bool {
		return data.Structs[i].Name < data.Structs[j].Name
	})
	sort.Slice(data.Imports, func(i, j int) bool {
		return data.Imports[i].Path < data.Imports[j].Path
	})

	return data
}

// resetExpr возвращает готовое выражение сброса для поля.
// expr — доступ к полю, например "x.gauge".
func resetExpr(expr string, t ast.Expr) string {
	switch tt := t.(type) {
	case *ast.Ident:
		switch tt.Name {
		case "int", "int8", "int16", "int32", "int64",
			"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
			"float32", "float64", "complex64", "complex128",
			"byte", "rune":
			return fmt.Sprintf("%s = 0", expr)
		case "string":
			return fmt.Sprintf("%s = \"\"", expr)
		case "bool":
			return fmt.Sprintf("%s = false", expr)
		default:
			// Именованный тип из этого же пакета.
			return fmt.Sprintf("if resetter, ok := any(&%s).(interface{ Reset() }); ok {\n\t\tresetter.Reset()\n\t}", expr)
		}

	case *ast.StarExpr:
		inner := resetExpr("*"+expr, tt.X)
		return fmt.Sprintf("if %s != nil {\n\t\t%s\n\t}", expr, inner)

	case *ast.ArrayType:
		if tt.Len == nil {
			// Слайс: обрезаем по длине.
			return fmt.Sprintf("%s = %s[:0]", expr, expr)
		}
		// Массив: обнуляем целиком.
		return fmt.Sprintf("%s = %s{}", expr, expr)

	case *ast.MapType:
		return fmt.Sprintf("clear(%s)", expr)

	case *ast.SelectorExpr:
		// Тип из другого пакета; для sync-типов мы сюда не попадаем.
		return fmt.Sprintf("if resetter, ok := any(&%s).(interface{ Reset() }); ok {\n\t\tresetter.Reset()\n\t}", expr)

	default:
		return fmt.Sprintf("var zero = *new(%s)\n\t%s = zero", expr, expr)
	}
}

// collectImports возвращает пакеты, которые нужно импортировать
// в сгенерированном файле (для типов полей вида pkg.Type).
func collectImports(pkg *pkgInfo) []importInfo {
	seen := map[string]bool{}
	var out []importInfo

	var walk func(ast.Expr)
	walk = func(t ast.Expr) {
		switch tt := t.(type) {
		case *ast.SelectorExpr:
			if ident, ok := tt.X.(*ast.Ident); ok {
				path := stdlibPath(ident.Name)
				if path == "" || seen[path] {
					return
				}
				seen[path] = true
				out = append(out, importInfo{Path: path, Name: ident.Name})
			}
		case *ast.StarExpr:
			walk(tt.X)
		case *ast.ArrayType:
			walk(tt.Elt)
		case *ast.MapType:
			walk(tt.Key)
			walk(tt.Value)
		}
	}

	for _, s := range pkg.structs {
		for _, f := range s.fields {
			if isSyncType(f.Type) {
				continue
			}
			walk(f.Type)
		}
	}
	return out
}

func stdlibPath(pkg string) string {
	switch pkg {
	case "sync":
		return "sync"
	case "time":
		return "time"
	case "context":
		return "context"
	case "atomic":
		return "sync/atomic"
	case "big":
		return "math/big"
	case "io":
		return "io"
	case "url":
		return "net/url"
	case "http":
		return "net/http"
	case "sql":
		return "database/sql"
	case "json":
		return "encoding/json"
	}
	return ""
}

func isSyncType(t ast.Expr) bool {
	sel, ok := t.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	ident, ok := sel.X.(*ast.Ident)
	if !ok {
		return false
	}
	full := ident.Name + "." + sel.Sel.Name
	return skipTypes[full]
}
