// Command reset генерирует методы Reset() для структур, помеченных
// комментарием // generate:reset.
//
// # Запуск
//
//	go run ./cmd/reset
//
// Утилита рекурсивно обходит все пакеты начиная с корневой директории
// проекта, находит структуры с директивой // generate:reset и генерирует
// для каждой метод Reset(), записывая результаты в reset.gen.go внутри
// соответствующего пакета.
//
// # Правила сброса
//
//   - примитивы (int, string, bool, ...) — к нулевому значению;
//   - слайсы — обрезаются по длине: s = s[:0];
//   - мапы — очищаются через clear(m);
//   - указатели — если не nil, то *ptr сбрасывается по тем же правилам;
//   - вложенные структуры — вызывают Reset(), если он у них есть;
//   - sync-типы (sync.Mutex, sync.RWMutex, sync.Once, sync.WaitGroup,
//     sync.Pool, sync.Cond) — пропускаются как не имеющие состояния;
//   - поля без имени (embed) — пропускаются.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const directive = "generate:reset"
const generatedFileName = "reset.gen.go"

// skipTypes — типы из пакета sync, которые не нужно сбрасывать.
// Присваивание zero value мьютексу или once может сломать синхронизацию.
var skipTypes = map[string]bool{
	"sync.Mutex":     true,
	"sync.RWMutex":   true,
	"sync.Once":      true,
	"sync.WaitGroup": true,
	"sync.Pool":      true,
	"sync.Cond":      true,
	"sync.Map":       true,
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "reset:", err)
		os.Exit(1)
	}
}

func run() error {
	root, err := os.Getwd()
	if err != nil {
		return fmt.Errorf("getwd: %w", err)
	}

	pkgs, err := scanPackages(root)
	if err != nil {
		return err
	}

	for _, pkg := range pkgs {
		if len(pkg.structs) == 0 {
			continue
		}
		if err := generateForPackage(pkg); err != nil {
			return fmt.Errorf("package %s: %w", pkg.name, err)
		}
	}
	return nil
}

type pkgInfo struct {
	dir     string
	name    string
	imports []importInfo // пакеты, которые нужно импортировать в reset.gen.go
	structs []*structInfo
}

type importInfo struct {
	path string
	name string // псевдоним, если нужен (обычно пусто)
}

type structInfo struct {
	name   string
	fields []*ast.Field
}

func scanPackages(root string) ([]*pkgInfo, error) {
	var pkgs []*pkgInfo

	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		base := filepath.Base(path)
		if base == "vendor" || base == ".git" || base == "testdata" || strings.HasPrefix(base, ".") {
			return filepath.SkipDir
		}

		pkg, err := parseDir(path)
		if err != nil {
			return err
		}
		if pkg != nil && len(pkg.structs) > 0 {
			pkgs = append(pkgs, pkg)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	return pkgs, nil
}

func parseDir(dir string) (*pkgInfo, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}

	fset := token.NewFileSet()
	var (
		pkgName string
		structs []*structInfo
	)

	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		name := e.Name()
		if !strings.HasSuffix(name, ".go") {
			continue
		}
		if strings.HasSuffix(name, "_test.go") || name == generatedFileName {
			continue
		}

		full := filepath.Join(dir, name)
		file, err := parser.ParseFile(fset, full, nil, parser.ParseComments)
		if err != nil {
			return nil, fmt.Errorf("parse %s: %w", full, err)
		}

		if pkgName == "" {
			pkgName = file.Name.Name
		}

		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			if !hasDirective(gd.Doc) {
				continue
			}
			for _, spec := range gd.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				st, ok := ts.Type.(*ast.StructType)
				if !ok {
					continue
				}
				structs = append(structs, &structInfo{
					name:   ts.Name.Name,
					fields: st.Fields.List,
				})
			}
		}
	}

	if pkgName == "" || len(structs) == 0 {
		return nil, nil
	}
	return &pkgInfo{dir: dir, name: pkgName, structs: structs}, nil
}

func hasDirective(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}
	for _, c := range doc.List {
		text := strings.TrimSpace(strings.TrimPrefix(c.Text, "//"))
		if strings.HasPrefix(text, directive) {
			return true
		}
	}
	return false
}

// generateForPackage генерирует reset.gen.go для одного пакета.
func generateForPackage(pkg *pkgInfo) error {
	// Собираем все импорты, которые могут понадобиться в сгенерированном
	// коде: смотрим на все поля всех структур и находим ссылки на внешние
	// пакеты (SelectorExpr вида pkg.Type).
	neededImports := collectImports(pkg)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by cmd/reset; DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkg.name)

	// Блок import, только если нужны внешние пакеты.
	if len(neededImports) > 0 {
		buf.WriteString("import (\n")
		// Сортируем импорты для детерминированного вывода.
		sort.Slice(neededImports, func(i, j int) bool {
			return neededImports[i].path < neededImports[j].path
		})
		for _, imp := range neededImports {
			fmt.Fprintf(&buf, "\t%q\n", imp.path)
		}
		buf.WriteString(")\n\n")
	}

	for _, s := range pkg.structs {
		writeResetMethod(&buf, s)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format: %w\nraw:\n%s", err, buf.String())
	}

	out := filepath.Join(pkg.dir, generatedFileName)
	return os.WriteFile(out, formatted, 0o644)
}

// collectImports находит все внешние пакеты, которые встречаются в типах
// полей структур, и возвращает список для блока import.
// Поля sync-типов пропускаются — они всё равно не генерируются в Reset().
func collectImports(pkg *pkgInfo) []importInfo {
	seen := map[string]bool{}
	var out []importInfo

	for _, s := range pkg.structs {
		for _, f := range s.fields {
			if isSyncType(f.Type) {
				continue
			}
			collectImportsFromType(f.Type, seen, &out)
		}
	}
	return out
}

func collectImportsFromType(t ast.Expr, seen map[string]bool, out *[]importInfo) {
	switch tt := t.(type) {
	case *ast.SelectorExpr:
		// Например, sync.Mutex — pkgName.Sel.
		if ident, ok := tt.X.(*ast.Ident); ok {
			// Известные нам пакеты с их реальными import-путями.
			path := stdlibPath(ident.Name)
			if path == "" {
				return
			}
			if seen[path] {
				return
			}
			seen[path] = true
			*out = append(*out, importInfo{path: path, name: ident.Name})
		}
	case *ast.StarExpr:
		collectImportsFromType(tt.X, seen, out)
	case *ast.ArrayType:
		collectImportsFromType(tt.Elt, seen, out)
	case *ast.MapType:
		collectImportsFromType(tt.Key, seen, out)
		collectImportsFromType(tt.Value, seen, out)
	}
}

// stdlibPath возвращает import-путь для известных стандартных пакетов.
// Покрываем минимум, который реально встречается в пользовательских
// структурах. Если пакет неизвестен — вернём пустую строку, и импорт
// не будет добавлен (пользователь допишет вручную).
func stdlibPath(pkg string) string {
	switch pkg {
	case "sync":
		return "sync"
	case "time":
		return "time"
	case "context":
		return "context"
	case "atomic":
		return "sync/atomic"
	case "big":
		return "math/big"
	case "io":
		return "io"
	case "url":
		return "net/url"
	case "http":
		return "net/http"
	case "sql":
		return "database/sql"
	case "json":
		return "encoding/json"
	}
	return ""
}

// writeResetMethod пишет метод Reset() для одной структуры.
func writeResetMethod(buf *bytes.Buffer, s *structInfo) {
	fmt.Fprintf(buf, "func (x *%s) Reset() {\n", s.name)
	buf.WriteString("\tif x == nil {\n\t\treturn\n\t}\n\n")

	for _, f := range s.fields {
		if len(f.Names) == 0 {
			continue
		}

		// Пропускаем sync-типы целиком.
		if isSyncType(f.Type) {
			continue
		}

		for _, name := range f.Names {
			writeFieldReset(buf, "x."+name.Name, f.Type)
		}
	}

	buf.WriteString("}\n\n")
}

// isSyncType возвращает true, если тип поля — sync.X из skipTypes.
func isSyncType(t ast.Expr) bool {
	sel, ok := t.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	ident, ok := sel.X.(*ast.Ident)
	if !ok {
		return false
	}
	full := ident.Name + "." + sel.Sel.Name
	return skipTypes[full]
}

// writeFieldReset пишет выражение сброса для одного поля.
func writeFieldReset(buf *bytes.Buffer, expr string, t ast.Expr) {
	switch tt := t.(type) {
	case *ast.Ident:
		writePrimitiveReset(buf, expr, tt.Name)

	case *ast.StarExpr:
		fmt.Fprintf(buf, "\tif %s != nil {\n", expr)
		writeFieldReset(buf, "*"+expr, tt.X)
		buf.WriteString("\t}\n")

	case *ast.ArrayType:
		// Массив [N]T — обнуляем через zero value.
		fmt.Fprintf(buf, "\t%s = %s{}\n", expr, typeName(t))

	case *ast.MapType:
		fmt.Fprintf(buf, "\tclear(%s)\n", expr)

	case *ast.StructType:
		fmt.Fprintf(buf, "\t%s = %s{}\n", expr, typeName(t))

	case *ast.SelectorExpr:
		// Тип из другого пакета. Для sync-типов сюда не попадаем
		// (отфильтрованы в writeResetMethod). Для остальных пробуем
		// вызвать Reset, иначе — zero value.
		fmt.Fprintf(buf, "\tif resetter, ok := any(&%s).(interface{ Reset() }); ok {\n", expr)
		buf.WriteString("\t\tresetter.Reset()\n")
		buf.WriteString("\t} else {\n")
		fmt.Fprintf(buf, "\t\t%s = %s{}\n", expr, typeName(t))
		buf.WriteString("\t}\n")

	default:
		fmt.Fprintf(buf, "\tvar zero %s\n\t%s = zero\n", typeName(t), expr)
	}
}

func writePrimitiveReset(buf *bytes.Buffer, expr, typeName string) {
	switch typeName {
	case "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
		"float32", "float64", "complex64", "complex128",
		"byte", "rune":
		fmt.Fprintf(buf, "\t%s = 0\n", expr)
	case "string":
		fmt.Fprintf(buf, "\t%s = \"\"\n", expr)
	case "bool":
		fmt.Fprintf(buf, "\t%s = false\n", expr)
	default:
		// Именованный тип из этого же пакета. Пробуем Reset через
		// interface, иначе — zero value.
		fmt.Fprintf(buf, "\tif resetter, ok := any(&%s).(interface{ Reset() }); ok {\n", expr)
		buf.WriteString("\t\tresetter.Reset()\n")
		buf.WriteString("\t} else {\n")
		fmt.Fprintf(buf, "\t\tvar zero %s\n\t\t%s = zero\n", typeName, expr)
		buf.WriteString("\t}\n")
	}
}

func typeName(t ast.Expr) string {
	switch tt := t.(type) {
	case *ast.Ident:
		return tt.Name
	case *ast.StarExpr:
		return "*" + typeName(tt.X)
	case *ast.SelectorExpr:
		return typeName(tt.X) + "." + tt.Sel.Name
	case *ast.ArrayType:
		if tt.Len == nil {
			return "[]" + typeName(tt.Elt)
		}
		return "[" + exprString(tt.Len) + "]" + typeName(tt.Elt)
	case *ast.MapType:
		return "map[" + typeName(tt.Key) + "]" + typeName(tt.Value)
	case *ast.StructType:
		return "struct{}"
	case *ast.InterfaceType:
		return "any"
	}
	return "any"
}

func exprString(e ast.Expr) string {
	switch tt := e.(type) {
	case *ast.BasicLit:
		return tt.Value
	case *ast.Ident:
		return tt.Name
	}
	return "0"
}
